import pandas as pd

def clean_dataset(input_filepath, final_output_filepath):
    print(f"Reading data from {input_filepath}...")
    df = pd.read_csv(input_filepath)
    
    # 1. Find all rows where 'is-MSA' is exactly 'no' (ignoring capitalization)
    mask = df['is-MSA'].str.strip().str.lower() == 'no'
    
    # 2. Replace the old MSA-sent with the new-MSA-sent for those specific rows
    df.loc[mask, 'MSA-sent'] = df.loc[mask, 'new-MSA-sent']
    
    # 3. Optional: Drop the 'is-MSA' and 'new-MSA-sent' columns to make the final file perfectly clean
    # Remove the '#' on the next line if you want to delete those columns
    df = df.drop(columns=['is-MSA', 'new-MSA-sent'])
    
    # 4. Save to the final CSV
    df.to_csv(final_output_filepath, index=False, encoding='utf-8-sig')
    print(f"Finished! Your updated dataset is saved to {final_output_filepath}")

# --- Run the script ---
if __name__ == "__main__":
    INPUT_FILE = "outputs/shami_correctness.csv"  # Generated by correct_data.py
    FINAL_OUTPUT = "data/shami_v2.csv"  # Corrected dataset
    
    clean_dataset(INPUT_FILE, FINAL_OUTPUT)